// Command notices writes THIRD-PARTY-NOTICES.md at the repository root.
//
//	go run ./scripts/notices          # rewrite the file
//	go run ./scripts/notices -check   # exit 1 when the file is stale
//
// Run it from the repository root, with ui/web/node_modules installed
// (pnpm install). The file has three parts:
//
//   - the hand-written notices for code read and adapted into this repository,
//     kept in scripts/notices/adapted.md;
//   - every Go module linked into the API binary, with its licence text in
//     full: a static binary carries no licence files of its own;
//   - every npm package in the web image's production install, by name and
//     licence. Their licence files travel with them in the image's
//     node_modules, so their texts are not repeated here.
//
// The output is deterministic (sorted, no dates), so -check compares bytes.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

const outFile = "THIRD-PARTY-NOTICES.md"

func main() {
	check := flag.Bool("check", false, "exit 1 if "+outFile+" is not what this would write")
	flag.Parse()

	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
}

func run(check bool) error {
	adapted, err := os.ReadFile("scripts/notices/adapted.md")
	if err != nil {
		return fmt.Errorf("run from the repository root: %w", err)
	}
	goPart, err := GoSection(".")
	if err != nil {
		return err
	}
	npmPart, err := npmSection("ui/web")
	if err != nil {
		return err
	}

	var b bytes.Buffer
	b.WriteString(header)
	b.Write(bytes.TrimRight(adapted, "\n"))
	b.WriteString("\n\n---\n\n")
	b.WriteString(goPart)
	b.WriteString("\n---\n\n")
	b.WriteString(npmPart)

	if check {
		current, err := os.ReadFile(outFile)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, b.Bytes()) {
			return fmt.Errorf("%s is stale: run go run ./scripts/notices", outFile)
		}
		return nil
	}
	return os.WriteFile(outFile, b.Bytes(), 0o644)
}

const header = `# Third-party notices

AnyTools is MIT licensed (see LICENSE). This file records the third-party code it contains or was
adapted from, and the licences that require their notices to travel with it.

It is generated by ` + "`go run ./scripts/notices`" + `; do not edit it by hand. The hand-written
sections come from ` + "`scripts/notices/adapted.md`" + `, and the dependency lists from ` + "`go list`" + ` and
` + "`pnpm licenses list --prod`" + `.

---

`

// module is one Go module as go list reports it.
type module struct {
	Path    string
	Version string
	Dir     string
	Main    bool
	Replace *module
}

// GoSection lists every module the API binary links, the Go toolchain's own
// standard library first, each with its licence and notice files in full.
// Identical texts are printed once, under every module that carries them.
func GoSection(root string) (string, error) {
	cmd := exec.Command("go", "list", "-deps", "-json=Module", "./cmd/...")
	cmd.Dir = root
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("go list: %w", err)
	}

	seen := map[string]module{}
	dec := json.NewDecoder(bytes.NewReader(out))
	for {
		var pkg struct{ Module *module }
		if err := dec.Decode(&pkg); err == io.EOF {
			break
		} else if err != nil {
			return "", fmt.Errorf("go list output: %w", err)
		}
		m := pkg.Module
		if m == nil || m.Main {
			continue // the standard library, or this repository
		}
		if m.Replace != nil {
			m.Dir = m.Replace.Dir
		}
		seen[m.Path] = *m
	}
	mods := make([]module, 0, len(seen))
	for _, m := range seen {
		mods = append(mods, m)
	}
	sort.Slice(mods, func(i, j int) bool { return mods[i].Path < mods[j].Path })

	goroot, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		return "", fmt.Errorf("go env GOROOT: %w", err)
	}
	// The toolchain's version is left out: it is pinned by go.mod, and
	// printing it would make the file depend on the machine that wrote it.
	mods = append([]module{{Path: "Go standard library", Dir: strings.TrimSpace(string(goroot))}}, mods...)

	type entry struct {
		name    string
		licence string
	}
	var rows []entry
	textOrder := []string{}
	byText := map[string][]string{}
	for _, m := range mods {
		files, err := licenceFiles(m.Dir)
		if err != nil {
			return "", err
		}
		if len(files) == 0 {
			return "", fmt.Errorf("%s has no licence file in %s", m.Path, m.Dir)
		}
		name := m.Path
		if m.Version != "" {
			name += " " + m.Version
		}
		var ids []string
		for _, f := range files {
			text := strings.TrimSpace(strings.ReplaceAll(f.text, "\r\n", "\n"))
			if id := spdx(text); id != "" {
				ids = append(ids, id)
			}
			if _, ok := byText[text]; !ok {
				textOrder = append(textOrder, text)
			}
			byText[text] = append(byText[text], name+" ("+f.name+")")
		}
		rows = append(rows, entry{name, strings.Join(dedupe(ids), ", ")})
	}

	var b strings.Builder
	b.WriteString("## Go modules in the API binary\n\n")
	b.WriteString("The API is one static binary, so the licence of every module it links is reproduced below.\n\n")
	b.WriteString("| Module | Licence |\n|---|---|\n")
	for _, r := range rows {
		lic := r.licence
		if lic == "" {
			lic = "see text below"
		}
		fmt.Fprintf(&b, "| %s | %s |\n", r.name, lic)
	}
	b.WriteString("\n")
	for _, text := range textOrder {
		b.WriteString("### " + strings.Join(byText[text], ", ") + "\n\n")
		b.WriteString("```\n" + text + "\n```\n\n")
	}
	return b.String(), nil
}

type licenceFile struct{ name, text string }

// licenceFiles returns a module's LICENSE, LICENCE, COPYING and NOTICE files
// at its root, sorted by name.
func licenceFiles(dir string) ([]licenceFile, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var files []licenceFile
	for _, e := range entries {
		lower := strings.ToLower(e.Name())
		// Source files such as lib/pq's notice.go are code, not notices.
		if strings.HasSuffix(lower, ".go") {
			continue
		}
		if e.IsDir() || !(strings.HasPrefix(lower, "licen") || strings.HasPrefix(lower, "copying") || strings.HasPrefix(lower, "notice")) {
			continue
		}
		b, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			return nil, err
		}
		files = append(files, licenceFile{e.Name(), string(b)})
	}
	sort.Slice(files, func(i, j int) bool { return files[i].name < files[j].name })
	return files, nil
}

// spdx names the common licences by their text. An unknown text returns "",
// and the table then points at the text itself.
func spdx(text string) string {
	t := strings.Join(strings.Fields(text), " ")
	switch {
	case strings.Contains(t, "Apache License") && strings.Contains(t, "Version 2.0"):
		return "Apache-2.0"
	case strings.Contains(t, "Mozilla Public License Version 2.0"):
		return "MPL-2.0"
	case strings.Contains(t, "Permission is hereby granted, free of charge"):
		return "MIT"
	case strings.Contains(t, "Permission to use, copy, modify, and/or distribute this software for any purpose"),
		strings.Contains(t, "Permission to use, copy, modify, and distribute this software for any purpose"):
		return "ISC"
	case strings.Contains(t, "Redistribution and use in source and binary forms"):
		if strings.Contains(t, "Neither the name") || strings.Contains(t, "names of its contributors") {
			return "BSD-3-Clause"
		}
		return "BSD-2-Clause"
	}
	return ""
}

func dedupe(ids []string) []string {
	var out []string
	for _, id := range ids {
		if len(out) == 0 || !contains(out, id) {
			out = append(out, id)
		}
	}
	return out
}

func contains(list []string, s string) bool {
	for _, x := range list {
		if x == s {
			return true
		}
	}
	return false
}

// npmSection lists the web image's production packages by licence. Paths are
// never printed: pnpm reports them as absolute paths on this machine.
func npmSection(web string) (string, error) {
	cmd := exec.Command("pnpm", "licenses", "list", "--prod", "--json")
	cmd.Dir = web
	cmd.Stderr = os.Stderr
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("pnpm licenses list (is ui/web/node_modules installed?): %w", err)
	}
	var byLicence map[string][]struct {
		Name     string   `json:"name"`
		Versions []string `json:"versions"`
		Paths    []string `json:"paths"`
		Homepage string   `json:"homepage"`
	}
	if err := json.Unmarshal(out, &byLicence); err != nil {
		return "", fmt.Errorf("pnpm licenses output: %w", err)
	}

	type row struct{ name, versions, licence, homepage string }
	var rows []row
	for licence, pkgs := range byLicence {
		for _, p := range pkgs {
			lic := licence
			// pnpm reads only package.json's "license"; a package that states
			// it in a LICENSE file alone is read here.
			if lic == "Unknown" && len(p.Paths) > 0 {
				if files, err := licenceFiles(p.Paths[0]); err == nil {
					for _, f := range files {
						if id := spdx(f.text); id != "" {
							lic = id
							break
						}
					}
				}
			}
			versions := append([]string(nil), p.Versions...)
			sort.Strings(versions)
			rows = append(rows, row{p.Name, strings.Join(versions, ", "), lic, p.Homepage})
		}
	}
	// One package can appear at two majors, so the sort key is the whole row.
	sort.Slice(rows, func(i, j int) bool {
		a, b := rows[i], rows[j]
		return a.name+"\x00"+a.versions+"\x00"+a.licence < b.name+"\x00"+b.versions+"\x00"+b.licence
	})

	var b strings.Builder
	b.WriteString("## npm packages in the web image\n\n")
	b.WriteString("The production install of `ui/web` (`pnpm install --prod`). Each package's own licence file\n")
	b.WriteString("ships with it in the image's `node_modules`.\n\n")
	b.WriteString("| Package | Version | Licence |\n|---|---|---|\n")
	for _, r := range rows {
		name := r.name
		if r.homepage != "" {
			name = "[" + r.name + "](" + r.homepage + ")"
		}
		fmt.Fprintf(&b, "| %s | %s | %s |\n", name, r.versions, r.licence)
	}
	return b.String(), nil
}
