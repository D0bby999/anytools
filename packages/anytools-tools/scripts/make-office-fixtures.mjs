/**
 * Generate the Office fixtures used to verify xlsx-to-csv and docx-to-markdown in a real
 * browser. Nothing here is committed: the files land in ../fixtures/ (gitignored).
 *
 *   office-book.xlsx  two sheets. Sheet "Data" carries the five cell shapes that break
 *                     converters — a date (must read 2026-09-03, never the serial 46264), a
 *                     formula with a cached result, rich text in two runs, a field holding
 *                     both a comma and a double quote, and an empty cell in the MIDDLE of a
 *                     row (a reader using eachCell closes that gap and shifts the row left).
 *   office-doc.docx   H1, H2, bold + italic, a bullet list, a link, and a 2x2 table whose
 *                     first row is NOT marked as a header row in the docx — the ordinary
 *                     case, and the one where a naive turndown pipeline emits raw <table>
 *                     HTML instead of a GFM table.
 *
 * Written with the same libraries the tools read with (exceljs) and with `docx`, a MIT
 * writer kept as a devDependency for exactly this.
 *
 * Run: pnpm --filter @anytools/tools exec node scripts/make-office-fixtures.mjs
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'fixtures');
mkdirSync(OUT, { recursive: true });

// --- office-book.xlsx -----------------------------------------------------------------------
{
  const mod = await import('exceljs');
  const ExcelJS = mod.default ?? mod;
  const wb = new ExcelJS.Workbook();

  const data = wb.addWorksheet('Data');
  data.addRow(['name', 'joined', 'score', 'note']);
  data.getCell('A2').value = { richText: [{ text: 'Ada ' }, { text: 'Lovelace' }] };
  data.getCell('B2').value = new Date(Date.UTC(2026, 8, 3));
  data.getCell('C2').value = 21;
  data.getCell('D2').value = 'Smith, "Bob"';
  data.getCell('A3').value = 'Grace Hopper';
  // B3 deliberately left empty — the hole in the middle.
  data.getCell('C3').value = { formula: 'C2*2', result: 42 };
  data.getCell('D3').value = 'plain';
  data.getCell('A4').value = 'Katherine Johnson';
  data.getCell('B4').value = new Date(Date.UTC(2026, 0, 31, 9, 15, 0));
  data.getCell('C4').value = { formula: 'C2/0', result: { error: '#DIV/0!' } };
  data.getCell('D4').value = 'line one\nline two';

  const notes = wb.addWorksheet('Notes');
  notes.addRow(['key', 'value']);
  notes.addRow(['source', 'generated by make-office-fixtures.mjs']);
  notes.addRow(['sheets', 'two, so the sheet picker has something to pick']);

  writeFileSync(join(OUT, 'office-book.xlsx'), await wb.xlsx.writeBuffer());
  console.log('wrote office-book.xlsx');
}

// --- office-doc.docx ------------------------------------------------------------------------
{
  const {
    Document,
    ExternalHyperlink,
    HeadingLevel,
    Packer,
    Paragraph,
    Table,
    TableCell,
    TableRow,
    TextRun,
  } = await import('docx');

  const cell = (text) => new TableCell({ children: [new Paragraph(text)] });

  const doc = new Document({
    sections: [
      {
        children: [
          new Paragraph({ text: 'Quarterly report', heading: HeadingLevel.HEADING_1 }),
          new Paragraph({ text: 'Summary', heading: HeadingLevel.HEADING_2 }),
          new Paragraph({
            children: [
              new TextRun({ text: 'Revenue was up', bold: true }),
              new TextRun({ text: ' but margins were flat.', italics: true }),
            ],
          }),
          new Paragraph({ text: 'First finding', bullet: { level: 0 } }),
          new Paragraph({ text: 'Second finding', bullet: { level: 0 } }),
          new Paragraph({
            children: [
              new ExternalHyperlink({
                children: [new TextRun('Source data')],
                link: 'https://example.com/report',
              }),
            ],
          }),
          new Paragraph({ text: 'Numbers', heading: HeadingLevel.HEADING_2 }),
          new Table({
            rows: [
              new TableRow({ children: [cell('Region'), cell('Revenue')] }),
              new TableRow({ children: [cell('North'), cell('120')] }),
              new TableRow({ children: [cell('South'), cell('98')] }),
            ],
          }),
        ],
      },
    ],
  });

  writeFileSync(join(OUT, 'office-doc.docx'), await Packer.toBuffer(doc));
  console.log('wrote office-doc.docx');
}
