#!/usr/bin/env bash
# run-local.sh — run AnyTools on this machine, the way the server runs it:
# production builds of the API and the web server, against a local Postgres.
#
#   deploy/scripts/run-local.sh          # build, migrate, run; Ctrl-C stops both
#   deploy/scripts/run-local.sh --init   # first time: write .env.local and create the database
#
# Reads .env.local (gitignored). --init generates its three secrets and turns
# on the development-only local sign-in (ANYTOOLS_DEV_LOGIN=1 with
# ANYTOOLS_ENV=development), so you can sign in before any OAuth app exists.
set -euo pipefail
cd "$(dirname "$0")/../.."
ENV_FILE=.env.local

if [ "${1:-}" = "--init" ]; then
  if [ -f "$ENV_FILE" ]; then
    echo "$ENV_FILE already exists; not overwriting it." >&2
  else
    cat > "$ENV_FILE" <<EOT
# Local review — generated by deploy/scripts/run-local.sh --init. Never commit.
ANYTOOLS_ENV=development
ANYTOOLS_POSTGRES_DSN=postgres://localhost:5432/anytools?sslmode=disable
ANYTOOLS_ENCRYPTION_KEY=$(openssl rand -hex 32)
ANYTOOLS_GATEWAY_TOKEN=$(openssl rand -hex 32)
ANYTOOLS_SESSION_SECRET=$(openssl rand -hex 32)
ANYTOOLS_SERVER_ADDR=127.0.0.1:8080
ANYTOOLS_API_URL=http://127.0.0.1:8080
ANYTOOLS_APP_URL=http://localhost:3000
ANYTOOLS_DATA_DIR=./data
# Development-only sign-in: a "Continue locally" button on /login.
ANYTOOLS_DEV_LOGIN=1
# Unofficial subscription sign-ins (ChatGPT, Gemini, Copilot, Claude) under
# Settings → Connections. Read docs/byok.md before turning on.
# ANYTOOLS_EXPERIMENTAL_SUBSCRIPTION_LANES=1
# Optional, once you have them (see .env.example for the redirect URIs):
# ANYTOOLS_GOOGLE_CLIENT_ID=
# ANYTOOLS_GOOGLE_CLIENT_SECRET=
# ANYTOOLS_GITHUB_CLIENT_ID=
# ANYTOOLS_GITHUB_CLIENT_SECRET=
EOT
    echo "wrote $ENV_FILE — back up ANYTOOLS_ENCRYPTION_KEY: without it, saved API keys cannot be read."
  fi
  createdb anytools 2>/dev/null && echo "created database anytools" || echo "database anytools already exists"
  exit 0
fi

[ -f "$ENV_FILE" ] || { echo "no $ENV_FILE — run: $0 --init" >&2; exit 2; }
set -a; . "./$ENV_FILE"; set +a
. deploy/scripts/legacy-env.sh

echo "building…"
GOTOOLCHAIN=auto go build -o ./anytools ./cmd/anytools
(cd ui/web && pnpm install --frozen-lockfile --prefer-offline >/dev/null && pnpm build >/dev/null)
./anytools migrate up

# Built-in transcription (up-methods phase 21): the same speaches image the
# server runs, on loopback, when Docker is here. Without Docker it is skipped
# and the built-in option does not appear; learners' own keys still work.
# ANYTOOLS_LOCAL_STT=0 skips it on purpose; a ANYTOOLS_STT_URL already set in
# .env.local is used as it is.
STT_IMAGE=ghcr.io/speaches-ai/speaches:0.8.3-cpu
STT_CONTAINER=""
if [ -n "${ANYTOOLS_STT_URL:-}" ] || [ "${ANYTOOLS_LOCAL_STT:-1}" = "0" ]; then
  :
elif command -v docker >/dev/null 2>&1 && docker info >/dev/null 2>&1; then
  echo "starting the built-in transcription engine ($STT_IMAGE)…"
  STT_CONTAINER=$(docker run -d --rm -p 127.0.0.1:8000:8000 \
    -v anytools-stt-models:/home/ubuntu/.cache/huggingface/hub \
    -e WHISPER__INFERENCE_DEVICE=cpu -e WHISPER__COMPUTE_TYPE=int8 -e ENABLE_UI=false \
    "$STT_IMAGE")
  for _ in $(seq 1 60); do curl -fsS http://127.0.0.1:8000/health >/dev/null 2>&1 && break; sleep 1; done
  curl -fsS -X POST "http://127.0.0.1:8000/v1/models/${ANYTOOLS_STT_MODEL:-Systran/faster-whisper-small}" >/dev/null \
    || echo "the transcription model could not be downloaded; the built-in option stays hidden" >&2
  export ANYTOOLS_STT_URL=http://127.0.0.1:8000
else
  echo "docker not found: skipping the built-in transcription engine (learners' own speech keys still work)."
fi

# Built-in voices (up-methods phase 22): the same Kokoro-FastAPI image the
# server runs, on loopback, when Docker is here; skipped without it, and the
# page then offers learners' own speech keys and the browser.
# ANYTOOLS_LOCAL_TTS=0 skips it on purpose; a ANYTOOLS_TTS_URL already set in
# .env.local is used as it is.
TTS_IMAGE=ghcr.io/remsky/kokoro-fastapi-cpu:v0.9.0@sha256:ee3111d6a2c903ed62f3b4fa19543c6901205ed39fce3c177e895b34a8386b9c
TTS_CONTAINER=""
if [ -n "${ANYTOOLS_TTS_URL:-}" ] || [ "${ANYTOOLS_LOCAL_TTS:-1}" = "0" ]; then
  :
elif command -v docker >/dev/null 2>&1 && docker info >/dev/null 2>&1; then
  echo "starting the built-in voices ($TTS_IMAGE)…"
  TTS_CONTAINER=$(docker run -d --rm -p 127.0.0.1:8880:8880 \
    -v anytools-tts-models:/app/api/src/models \
    "$TTS_IMAGE")
  for _ in $(seq 1 120); do curl -fsS http://127.0.0.1:8880/health >/dev/null 2>&1 && break; sleep 1; done
  export ANYTOOLS_TTS_URL=http://127.0.0.1:8880
else
  echo "docker not found: skipping the built-in voices (learners' own speech keys and the browser still work)."
fi

./anytools serve &
API_PID=$!
trap 'kill $API_PID 2>/dev/null; [ -n "$STT_CONTAINER" ] && docker stop "$STT_CONTAINER" >/dev/null 2>&1; [ -n "$TTS_CONTAINER" ] && docker stop "$TTS_CONTAINER" >/dev/null 2>&1' EXIT INT TERM
for _ in $(seq 1 30); do curl -fsS "$ANYTOOLS_API_URL/health" >/dev/null 2>&1 && break; sleep 0.5; done

echo "AnyTools: $ANYTOOLS_APP_URL  (Ctrl-C stops the API and the web server)"
cd ui/web && NODE_ENV=production PORT=3000 node_modules/.bin/react-router-serve ./build/server/index.js
